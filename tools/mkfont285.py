# Zhekov), read from its BDF, into app/font285.c: font_t (8 x 16, the labels, the values) and font_T (the same glyphs
# at 2x, 16 x 32: the big values, the titles). 1 bit a pixel, each glyph cropped to its ink, in the order gfx.c's
# glyph_of counts them (ASCII 32..95, the accented capitals, the arrow, the dot, m b d i s u).
#   tools/mkfont285.py FONT.bdf OUT.c
import sys

CHARS = [chr(c) for c in range(32, 96)] + ['É', 'È', 'À', 'Ç', 'Ê', '→', '·'] + list('mbdisu')


def read_bdf(path):
    lines = open(path, encoding='latin-1').read().splitlines()
    fbb = next(l for l in lines if l.startswith('FONTBOUNDINGBOX')).split()
    cw, ch, fx, fy = int(fbb[1]), int(fbb[2]), int(fbb[3]), int(fbb[4])
    base = ch + fy                                   # rows above the baseline
    out, i = {}, 0
    while i < len(lines):
        if lines[i].startswith('ENCODING'):
            code = int(lines[i].split()[1])
            j = i
            while not lines[j].startswith('BBX'):
                j += 1
            bw, bh, bx, by = map(int, lines[j].split()[1:5])
            while not lines[j].startswith('BITMAP'):
                j += 1
            rows = []
            for r in range(bh):
                v = int(lines[j + 1 + r], 16)
                nb = (len(lines[j + 1 + r]) * 4)
                rows.append([(v >> (nb - 1 - x)) & 1 for x in range(bw)])
            cell = [[0] * cw for _ in range(ch)]
            top = base - (by + bh)                   # the glyph's first row in the cell
            for r in range(bh):
                for x in range(bw):
                    yy, xx = top + r, bx + x
                    if 0 <= yy < ch and 0 <= xx < cw and rows[r][x]:
                        cell[yy][xx] = 1
            out[code] = cell
            i = j + bh
        i += 1
    return out, cw, ch, base


def build(name, cells, cw, ch, base, s):
    bits, glyphs = [], []
    for c in CHARS:
        cell = cells.get(ord(c)) or cells.get(ord('?'))
        ys = [y for y in range(ch) if any(cell[y])]
        xs = [x for x in range(cw) if any(cell[y][x] for y in range(ch))]
        if not ys:
            glyphs.append((0, 0, 0, 0, cw * s, len(bits) // 8)); continue
        y0, y1, x0, x1 = ys[0], ys[-1] + 1, xs[0], xs[-1] + 1
        while len(bits) % 8:
            bits.append(0)
        off = len(bits) // 8
        for y in range(y0 * s, y1 * s):
            for x in range(x0 * s, x1 * s):
                bits.append(cell[y // s][x // s])
        glyphs.append(((x1 - x0) * s, (y1 - y0) * s, x0 * s, y0 * s, cw * s, off))
    while len(bits) % 8:
        bits.append(0)
    data = [int(''.join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)] + [0, 0]
    H = cells[ord('H')]
    hy = [y for y in range(ch) if any(H[y])]
    cap_top, cap = hy[0] * s, (hy[-1] + 1 - hy[0]) * s
    o = [f'static const uint8_t {name}_bits[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        o.append('    ' + ','.join(str(v) for v in data[i:i + 24]) + ',')
    o.append('};')
    o.append(f'static const gfx_glyph {name}_g[{len(glyphs)}] = {{')
    for (w, h, x, y, adv, off) in glyphs:
        o.append(f'    {{ {w}, {h}, {x}, {y}, {adv}, {off} }},')
    o.append('};')
    o.append(f'const gfx_font {name} = {{ {name}_g, {name}_bits, {len(glyphs)}, {base * s}, {ch * s}, {cap}, {cap_top}, 1 }};')
    return '\n'.join(o)


cells, cw, ch, base = read_bdf(sys.argv[1])
src = ['/* SPDX-License-Identifier: GPL-3.0-only',
       ' * Generated by tools/mkfont285.py: do not edit.',
       ' * Glyphs from Terminus Bold 8x16, (c) Dimitar Toshkov Zhekov, SIL Open Font License 1.1 (as SLOOP 2.8.5). */',
       '#include "gfx.h"', '',
       build('font_t', cells, cw, ch, base, 1), '',
       build('font_T', cells, cw, ch, base, 2), '']
open(sys.argv[2], 'w').write('\n'.join(src))
