#!/usr/bin/env python3
# The screen's fonts, rendered from Inter Bold (SIL Open Font License 1.1, (c) The Inter Project Authors) into
# anti-aliased bitmaps for app/fonts.c, each glyph cropped to its ink: 3 bits a pixel for the small size (where
# the edges matter most; 4 until 3.1.5), 2 for the others, the bits one after the other across the bytes; the big size holds only what is written big (digits, capitals).
#   tools/mkfont.py OUT.c
import sys
from PIL import Image, ImageDraw, ImageFont
FONT = '/usr/share/fonts/opentype/inter/Inter-Bold.otf'
# ASCII 32..95, then the accented capitals French needs (ui text is UTF-8: gfx.c maps them to these codes)
CHARS = [chr(c) for c in range(32, 96)] + ['É', 'È', 'À', 'Ç', 'Ê', '→', '·'] + list('mbdisu')   # (chord names: Dm, Bdim, Csus)
SIZES = [('font_s', 18, 2, set(c for c in CHARS if c not in 'ÉÈÀÇÊ')),   # (4.0.1: 2 bits, as the others: the room before the sample bank)
         ('font_m', 24, 2, set([chr(c) for c in range(32, 96) if chr(c) not in '!"$&*;@[\\]^_'] + ['·', '→'])),   # (4.0.1: values, messages: no accents, small letters, rare signs)
         ('font_l', 34, 2, set('0123456789 ABCDEFGHIJKLMNOPQRSTUVWXYZ.:-/%+#·'))]   # (4.0.1: no accents: the interface is in English)

def build(name, px, bpp, subset):
    f = ImageFont.truetype(FONT, px)
    asc, desc = f.getmetrics()
    glyphs, bits = [], bytearray()
    for ch in CHARS:
        adv = round(f.getlength(ch))
        im = Image.new('L', (px * 3, px * 3), 0)
        ImageDraw.Draw(im).text((px, px), ch, font=f, fill=255)
        bb = im.getbbox()
        if not bb or (subset is not None and ch not in subset):
            glyphs.append((0, 0, 0, 0, adv, len(bits))); continue
        x0, y0, x1, y1 = bb
        w, h = x1 - x0, y1 - y0
        off = len(bits)
        nib = []
        for y in range(y0, y1):
            for x in range(x0, x1):
                nib.append((im.getpixel((x, y)) * ((1 << bpp) - 1) + 127) // 255)
        acc = n = 0                                    # (MSB first, a glyph from a byte's start)
        for v in nib:
            acc = acc << bpp | v; n += bpp
            while n >= 8: n -= 8; bits.append(acc >> n & 255)
        if n: bits.append(acc << (8 - n) & 255)
        glyphs.append((w, h, x0 - px, y0 - px, adv, off))   # offsets from the pen (top of the em box)
    return asc, desc, glyphs, bits

out = ['/* SPDX-License-Identifier: GPL-3.0-only', ' * Generated by tools/mkfont.py: do not edit.',
       ' * Glyphs rendered from Inter Bold, (c) The Inter Project Authors, SIL Open Font License 1.1. */',
       '#include "gfx.h"', '']
total = 0
for name, px, bpp, subset in SIZES:
    asc, desc, glyphs, bits = build(name, px, bpp, subset)
    bits.append(0)                                   # (gfx.c reads two bytes at a time)
    total += len(bits) + 8 * len(glyphs)
    out.append(f'static const uint8_t {name}_bits[{len(bits)}] = {{')
    for i in range(0, len(bits), 24): out.append('    ' + ','.join(str(b) for b in bits[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const gfx_glyph {name}_g[{len(glyphs)}] = {{')
    for g in glyphs: out.append('    {%d,%d,%d,%d,%d,%d},' % g)
    out.append('};')
    # cap height: the H's ink
    H = glyphs[ord('H') - 32]
    out.append(f'const gfx_font {name} = {{ {name}_g, {name}_bits, {len(glyphs)}, {asc}, {asc + desc}, {H[1]}, {H[3]}, {bpp} }};')
    out.append('')
    print(f'{name}: {px} px, cap {H[1]}, {len(bits)} bytes, ' + ' '.join(f'{c}={g[4]}' for c, g in zip(CHARS, glyphs) if c in 'M0A ').strip(), file=sys.stderr)
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print(f'total {total} bytes', file=sys.stderr)
